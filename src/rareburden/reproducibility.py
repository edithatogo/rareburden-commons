def _safe_evidence_path(root: Path, value: str) -> Path:
    path = PurePosixPath(value.removesuffix("/"))
    if not value or path.is_absolute() or ".." in path.parts or "\\" in value:
        raise ReproducibilityAssessmentError(
            f"Unsafe reproducibility evidence path: {value!r}"
        )
    root_resolved = root.expanduser().resolve()
    candidate = root_resolved / path.as_posix()
    try:
        candidate.resolve().relative_to(root_resolved)
    except ValueError as exc:
        raise ReproducibilityAssessmentError(
            f"Reproducibility evidence escapes package root: {value}"
        ) from exc
    return candidate


def verify_reproducibility_assessment(
    assessment: Mapping[str, Any],
    *,
    root: Path | None = None,
    expected_release_id: str | None = None,
    expected_workflow_run_id: str | None = None,
) -> list[str]:
    """Verify assessment identity, level gates, and locally asserted evidence."""
    failures: list[str] = []
    core = {
        key: value
        for key, value in assessment.items()
        if key not in {"schema_version", "reproducibility_assessment_id"}
    }
    try:
        expected_identifier = content_id("repro", core)
    except Exception as exc:
        failures.append(f"unable to recompute reproducibility assessment identifier: {exc}")
    else:
        if assessment.get("reproducibility_assessment_id") != expected_identifier:
            failures.append("reproducibility assessment content identifier mismatch")

    if expected_release_id is not None and assessment.get("release_id") != expected_release_id:
        failures.append("reproducibility assessment refers to the wrong release")
    if (
        expected_workflow_run_id is not None
        and assessment.get("workflow_run_id") != expected_workflow_run_id
    ):
        failures.append("reproducibility assessment refers to the wrong workflow run")
    if assessment.get("external_approval_claimed") is not False:
        failures.append("internal assessment must not claim external approval")

    criteria = assessment.get("criteria")
    if not isinstance(criteria, list):
        return [*failures, "reproducibility criteria must be a list"]
    try:
        rebuilt = build_reproducibility_assessment(
            release_id=str(assessment.get("release_id", "")),
            workflow_run_id=str(assessment.get("workflow_run_id", "")),
            created_at=str(assessment.get("created_at", "")),
            criteria=[item for item in criteria if isinstance(item, Mapping)],
            claimed_level=str(assessment.get("claimed_level", "")),
            limitations=[str(item) for item in assessment.get("limitations", [])],
        )
    except (TypeError, ReproducibilityAssessmentError) as exc:
        failures.append(f"reproducibility level gate failed: {exc}")
    else:
        if rebuilt != dict(assessment):
            failures.append("reproducibility assessment differs from canonical rebuild")

    if root is None:
        return sorted(set(failures))
    for criterion in criteria:
        if not isinstance(criterion, Mapping) or criterion.get("status") != "met":
            continue
        for evidence in criterion.get("evidence", []):
            value = str(evidence)
            parsed = urlparse(value)
            if parsed.scheme:
                if parsed.scheme != "https" or not parsed.netloc:
                    failures.append(f"unsupported external evidence identifier: {value}")
                continue
            try:
                path = _safe_evidence_path(root, value)
            except ReproducibilityAssessmentError as exc:
                failures.append(str(exc))
                continue
            if value.endswith("/"):
                if path.is_symlink() or not path.is_dir() or not any(path.iterdir()):
                    failures.append(f"evidence directory is missing or empty: {value}")
            elif path.is_symlink() or not path.is_file():
                failures.append(f"evidence file is missing or unsafe: {value}")
    return sorted(set(failures))


