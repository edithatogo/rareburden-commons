"""Machine-readable, non-self-congratulatory reproducibility assessments.

The assessment deliberately distinguishes structural evidence generated by the project
from independent reproduction, external scientific validation, legal review, and
empirical replication.  Passing local checks is never represented as external approval.
"""

from __future__ import annotations

from collections.abc import Mapping, Sequence
from pathlib import Path, PurePosixPath
from typing import Any
from urllib.parse import urlparse

from rareburden.provenance import content_id


class ReproducibilityAssessmentError(ValueError):
    """Raised when a reproducibility assessment would be incomplete or misleading."""


_LEVEL_ORDER = {
    "R0_conceptual": 0,
    "R1_rerunnable": 1,
    "R2_auditable": 2,
    "R3_independently_reproduced": 3,
    "R4_externally_replicated": 4,
}
_ALLOWED_STATUS = {"met", "partially_met", "not_met", "not_applicable"}


def _criterion(
    *,
    criterion_id: str,
    title: str,
    status: str,
    evidence: Sequence[str],
    rationale: str,
    independently_verified: bool = False,
) -> dict[str, Any]:
    if status not in _ALLOWED_STATUS:
        raise ReproducibilityAssessmentError(f"Unsupported criterion status: {status}")
    cleaned_evidence = sorted({str(item).strip() for item in evidence if str(item).strip()})
    if status == "met" and not cleaned_evidence:
        raise ReproducibilityAssessmentError(
            f"Met criterion {criterion_id} requires machine-inspectable evidence"
        )
    if independently_verified and status != "met":
        raise ReproducibilityAssessmentError(
            f"Criterion {criterion_id} cannot be independently verified unless met"
        )
    return {
        "criterion_id": criterion_id,
        "title": title,
        "status": status,
        "evidence": cleaned_evidence,
        "rationale": rationale,
        "independently_verified": independently_verified,
    }


def build_reproducibility_assessment(
    *,
    release_id: str,
    workflow_run_id: str,
    created_at: str,
    criteria: Sequence[Mapping[str, Any]],
    claimed_level: str,
    limitations: Sequence[str],
) -> dict[str, Any]:
    """Build a content-addressed assessment with conservative level gating."""
    if claimed_level not in _LEVEL_ORDER:
        raise ReproducibilityAssessmentError(f"Unsupported reproducibility level: {claimed_level}")
    records: list[dict[str, Any]] = []
    seen: set[str] = set()
    for raw in criteria:
        identifier = str(raw.get("criterion_id", "")).strip()
        if not identifier or identifier in seen:
            raise ReproducibilityAssessmentError(
                "Reproducibility criterion identifiers must be unique and non-empty"
            )
        seen.add(identifier)
        records.append(
            _criterion(
                criterion_id=identifier,
                title=str(raw.get("title", "")).strip(),
                status=str(raw.get("status", "")).strip(),
                evidence=[str(item) for item in raw.get("evidence", [])],
                rationale=str(raw.get("rationale", "")).strip(),
                independently_verified=bool(raw.get("independently_verified", False)),
            )
        )
    if not records:
        raise ReproducibilityAssessmentError("At least one reproducibility criterion is required")
    records.sort(key=lambda item: str(item["criterion_id"]))
    by_id = {str(item["criterion_id"]): item for item in records}
    required_for_level = {
        "R1_rerunnable": {
            "source_identity",
            "software_identity",
            "environment_identity",
            "deterministic_execution",
        },
        "R2_auditable": {
            "prospective_protocol",
            "decision_and_deviation_log",
            "activity_level_provenance",
            "lineage_closure",
            "research_object",
            "reporting_evidence",
        },
        "R3_independently_reproduced": {"independent_reproduction"},
        "R4_externally_replicated": {"external_replication"},
    }
    for level, position in _LEVEL_ORDER.items():
        if position == 0 or position > _LEVEL_ORDER[claimed_level]:
            continue
        for required in required_for_level.get(level, set()):
            record = by_id.get(required)
            if record is None or record["status"] != "met":
                raise ReproducibilityAssessmentError(
                    f"Claimed level {claimed_level} requires met criterion {required}"
                )
            if (
                level in {"R3_independently_reproduced", "R4_externally_replicated"}
                and not record["independently_verified"]
            ):
                raise ReproducibilityAssessmentError(
                    "Claimed level "
                    f"{claimed_level} requires independent verification for {required}"
                )
    summary = {
        status: sum(item["status"] == status for item in records)
        for status in sorted(_ALLOWED_STATUS)
    }
    core = {
        "release_id": release_id,
        "workflow_run_id": workflow_run_id,
        "created_at": created_at,
        "assessment_method": "automated_internal_structural_assessment",
        "claimed_level": claimed_level,
        "criteria": records,
        "summary": summary,
        "limitations": sorted({str(item).strip() for item in limitations if str(item).strip()}),
        "external_approval_claimed": False,
    }
    return {
        "schema_version": "1.0.0",
        "reproducibility_assessment_id": content_id("repro", core),
        **core,
    }


